# Registers Chispa at logon by default, or at boot with same-account credentials.
#
# Why a scheduled task and not a Windows service: the service keeps its data under
# .local/server and protects its Data Protection keys with DPAPI, which is bound to the Windows
# account that created them. A real service would have to run as that account with its profile
# loaded; a scheduled task does that naturally, and Task Scheduler already provides
# restart-on-failure, so no wrapper binary or service host is added to the deployment.
#
#   .\tools\install-service.ps1 -DryRun                  # 只打印将要写入的内容，不注册
#   .\tools\install-service.ps1 -Production              # 正式配置（Secure Cookie + 可信代理）
#   .\tools\install-service.ps1 -Trigger AtStartup -Credential (Get-Credential) # 无人登录启动
#
# The script refuses to replace an existing task unless -Force is given: a second definition on
# the same machine would race the first one for port 5115.

param(
    [string]$TaskName = 'Chispa.Server',
    [string]$DataRoot = '',
    [string]$ServerUrl = 'http://127.0.0.1:5115',
    [string]$LogDirectory = '',
    [string]$TrustedProxies = '127.0.0.1',
    [string]$ReleaseTrustKeys = '',
    [string]$ServiceDirectory = '',
    [string]$ServerDll = '',
    [string]$LauncherVersion = '',
    [string]$LauncherMinimum = '',
    [string]$LauncherDownloadUrl = '',
    [string]$LauncherNotes = '',
    [System.Management.Automation.PSCredential]$Credential,
    [ValidateSet('AtStartup', 'AtLogOn')]
    [string]$Trigger = 'AtLogOn',
    [switch]$Production,
    [switch]$DryRun,
    [switch]$Force
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$localDotnet = Join-Path $root '.tooling/dotnet/dotnet.exe'
$dotnet = if (Test-Path -LiteralPath $localDotnet) { $localDotnet } else { (Get-Command dotnet -ErrorAction Stop).Source }
$pointer = Join-Path $root '.local/current-server-build.txt'
$serverDll = if ($ServerDll) { [IO.Path]::GetFullPath($ServerDll) } elseif (Test-Path -LiteralPath $pointer) {
    $buildId = [System.IO.File]::ReadAllText($pointer).Trim()
    Join-Path $root ".local/server-builds/$buildId/Chispa.Server.dll"
} else {
    Join-Path $root 'server/bin/Release/net10.0/Chispa.Server.dll'
}
if (-not (Test-Path -LiteralPath $serverDll)) { throw "Server build not found: $serverDll. Run ./build.ps1 first." }
if (-not $DataRoot) { $DataRoot = Join-Path $root '.local/server' }
if (-not $LogDirectory) { $LogDirectory = Join-Path $DataRoot 'logs' }
if (-not $ReleaseTrustKeys -and (Test-Path -LiteralPath (Join-Path $DataRoot 'release-trust.json'))) {
    $ReleaseTrustKeys = Join-Path $DataRoot 'release-trust.json'
}

# Interactive tasks cannot run before Windows login. True startup needs a password-backed
# task under the SAME identity that owns the existing DPAPI key ring.
if ($Trigger -eq 'AtStartup' -and -not $Credential -and -not $DryRun) {
    throw 'AtStartup requires -Credential (Get-Credential) for the current Windows account. Use AtLogOn for an interactive task.'
}
if ($Credential) {
    $account = New-Object Security.Principal.NTAccount($Credential.UserName)
    $credentialSid = $account.Translate([Security.Principal.SecurityIdentifier]).Value
    if ($credentialSid -ne [Security.Principal.WindowsIdentity]::GetCurrent().User.Value) {
        throw 'Use the current Windows identity: the existing DPAPI key ring belongs to it.'
    }
}

# ---- already installed? ----------------------------------------------------------------------
$existing = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
if ($existing -and -not $Force) {
    $info = Get-ScheduledTaskInfo -TaskName $TaskName
    Write-Output "任务 '$TaskName' 已经存在，不重复安装。"
    Write-Output ("  状态           : {0}" -f $existing.State)
    Write-Output ("  上次运行时间   : {0}" -f $info.LastRunTime)
    Write-Output ("  上次结果       : {0}" -f $info.LastTaskResult)
    Write-Output ("  下次运行时间   : {0}" -f $info.NextRunTime)
    Write-Output '  如需替换，请先运行 ./tools/uninstall-service.ps1，或加 -Force。'
    exit 0
}

if ($existing -and $existing.State -eq 'Running') { throw 'Stop the running task before replacing its launcher.' }

# ---- launcher --------------------------------------------------------------------------------
# A wrapper, because a scheduled task cannot set environment variables itself. It is generated
# rather than hand-edited so the values registered now are visible in one place (`-DryRun` prints
# it), and so a re-install cannot leave a stale variable from an older layout.
$serviceDirectory = if ($ServiceDirectory) { $ServiceDirectory } else { Join-Path $root '.local/service' }
$launcher = Join-Path $serviceDirectory 'start-chispa-server.ps1'
$productionValue = if ($Production) { '1' } else { '0' }
function Quote-Literal([string]$value) { return $value.Replace("'", "''") }
$launcherText = @"
# Generated by tools/install-service.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss'). Do not edit:
# change the installer arguments and re-run it, so the task and this file cannot disagree.
`$ErrorActionPreference = 'Stop'
Set-Location '$(Quote-Literal $root)'
`$env:CHISPA_SERVER_DATA = '$(Quote-Literal $DataRoot)'
`$env:CHISPA_SERVER_URL = '$(Quote-Literal $ServerUrl)'
`$env:CHISPA_LOG_DIRECTORY = '$(Quote-Literal $LogDirectory)'
`$env:CHISPA_LOG_LEVEL = 'Information'
`$env:CHISPA_TRUSTED_PROXIES = '$(Quote-Literal $TrustedProxies)'
`$env:CHISPA_PRODUCTION = '$productionValue'
`$env:CHISPA_RELEASE_TRUST_KEYS = '$(Quote-Literal $ReleaseTrustKeys)'
`$env:CHISPA_LAUNCHER_VERSION = '$(Quote-Literal $LauncherVersion)'
`$env:CHISPA_LAUNCHER_MINIMUM = '$(Quote-Literal $LauncherMinimum)'
`$env:CHISPA_LAUNCHER_DOWNLOAD_URL = '$(Quote-Literal $LauncherDownloadUrl)'
`$env:CHISPA_LAUNCHER_NOTES = '$(Quote-Literal $LauncherNotes)'
`$env:DOTNET_CLI_HOME = '$(Quote-Literal (Join-Path $root '.tooling/home'))'
`$env:DOTNET_NOLOGO = '1'
& '$(Quote-Literal $dotnet)' '$(Quote-Literal $serverDll)'
exit `$LASTEXITCODE
"@

$arguments = '-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "{0}"' -f $launcher
$watchdog = Join-Path $root 'tools/run-server-watchdog.ps1'
$stopFlagForDisplay = Join-Path $serviceDirectory 'stop.flag'
$watchdogLog = Join-Path $LogDirectory 'watchdog.log'
$watchdogArguments = '-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "{0}" -Launcher "{1}" -StopFlag "{2}" -LogFile "{3}"' -f `
    $watchdog, $launcher, $stopFlagForDisplay, (Join-Path $LogDirectory 'watchdog.log')

if ($DryRun) {
    Write-Output "=== 将写入 $launcher ==="
    $launcherText
    Write-Output '=== 将注册的计划任务 ==='
    Write-Output ("  名称     : {0}" -f $TaskName)
    Write-Output ("  触发器   : {0}" -f $Trigger)
    Write-Output ("  动作     : powershell.exe {0}" -f $watchdogArguments)
    Write-Output ("  运行身份 : {0}\{1}（当前账号，DPAPI 密钥与它绑定）" -f $env:USERDOMAIN, $env:USERNAME)
    Write-Output '  崩溃恢复 : 监视进程在服务退出后 5 秒重新拉起；任务本身失败时每分钟重试'
    Write-Output ('  登录模式 : ' + $(if ($Trigger -eq 'AtStartup') { 'Password (requires -Credential before installation)' } else { 'Interactive (requires Windows login)' }))
    Write-Output '  未做任何修改。'
    exit 0
}

New-Item -ItemType Directory -Force $serviceDirectory | Out-Null
Set-Content -LiteralPath $launcher -Value $launcherText -Encoding UTF8
Write-Output "launcher: $launcher"

# ---- registration ----------------------------------------------------------------------------
# The task runs the watchdog, not the server: the watchdog is what notices a crashed child and
# starts it again (measured: Task Scheduler's own restart-on-failure did not fire for a terminated
# child on this machine). Task Scheduler then only has to keep one small loop alive.
$stopFlag = Join-Path $serviceDirectory 'stop.flag'
if (Test-Path -LiteralPath $stopFlag) { Remove-Item -LiteralPath $stopFlag -Force }
$action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument $watchdogArguments -WorkingDirectory $root
$taskTrigger = if ($Trigger -eq 'AtStartup') { New-ScheduledTaskTrigger -AtStartup } else { New-ScheduledTaskTrigger -AtLogOn -User "$env:USERNAME" }
$principal = New-ScheduledTaskPrincipal -UserId "$env:USERDOMAIN\$env:USERNAME" -LogonType Interactive -RunLevel Limited
$settings = New-ScheduledTaskSettingsSet `
    -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
    -StartWhenAvailable `
    -MultipleInstances IgnoreNew `
    -RestartCount 999 `
    -RestartInterval (New-TimeSpan -Minutes 1) `
    -ExecutionTimeLimit (New-TimeSpan -Seconds 0)

try {
    if ($existing -and $existing.State -eq 'Running') {
        throw 'The existing task is running. Stop it in a maintenance window before replacing it.'
    }
    $registration = @{
        TaskName = $TaskName; Action = $action; Trigger = $taskTrigger; Settings = $settings
        Description = 'Chispa license service: watchdog + auto start'; Force = [bool]$Force
    }
    if ($Trigger -eq 'AtStartup') {
        $registration.User = $Credential.UserName
        $registration.Password = $Credential.GetNetworkCredential().Password
        $registration.RunLevel = 'Limited'
    } else { $registration.Principal = $principal }
    try { Register-ScheduledTask @registration | Out-Null }
    finally { $registration.Remove('Password'); $Credential = $null }

} catch {
    throw ("注册计划任务失败：{0}。开机触发（AtStartup）需要管理员权限；在普通权限下请用 -Trigger AtLogOn。" -f $_.Exception.Message)
}

$registered = Get-ScheduledTask -TaskName $TaskName
$info = Get-ScheduledTaskInfo -TaskName $TaskName
Write-Output ("已注册任务 {0}：" -f $TaskName)
Write-Output ("  触发器   : {0}" -f $Trigger)
Write-Output ("  状态     : {0}" -f $registered.State)
Write-Output ("  下次运行 : {0}" -f $info.NextRunTime)
Write-Output ("  监视日志 : {0}" -f $watchdogLog)
Write-Output ''
Write-Output '验证步骤：'
Write-Output ('  Start-ScheduledTask -TaskName {0}' -f $TaskName)
Write-Output ("  Invoke-WebRequest " + $ServerUrl.TrimEnd('/').ToString() + "/ready -UseBasicParsing   # 期望 200 {""status"":""ready""}")
Write-Output ('  # 模拟崩溃：结束服务进程，约 5 秒后监视进程会重新拉起它')
Write-Output ('  $p = (Get-NetTCPConnection -LocalPort {0} -State Listen).OwningProcess; Stop-Process -Id $p -Force' -f ([Uri]$ServerUrl).Port)
Write-Output ("  Get-Content '{0}' -Tail 5" -f $watchdogLog)
Write-Output '停止与卸载：./tools/uninstall-service.ps1（会先写停止标志，让服务正常退出）'
